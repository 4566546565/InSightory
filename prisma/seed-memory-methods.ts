async function main() {
  console.log("开始添加记忆方法指南...");

  for (const method of memoryMethods) {
    await db.studyGuide.create({
      data: {
        title: method.title,
        category: method.category,
        description: method.description,
        content: method.content,
        tags: method.tags,
        viewCount: method.viewCount,
      },
    });
    console.log(`✓ 已添加: ${method.title}`);
  }

  console.log(`\n完成！共添加 ${memoryMethods.length} 个记忆方法指南`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
