import { PrismaClient } from "@prisma/client";

const db = new PrismaClient();

function doc(...ps: string[]) {
  return { type: "doc", content: ps.map((t) => ({ type: "paragraph", content: [{ type: "text", text: t }] })) };
}

async function main() {
  console.log("开始为选择性必修2课程添加内容...\n");

  const textbook = await db.textbook.findFirst({
    where: { title: { contains: "选择性必修2" } },
  });
  if (!textbook) { console.error("未找到教材"); return; }

  const lessons = await db.lesson.findMany({
    where: { unit: { textbookId: textbook.id } },
    orderBy: { lessonNumber: "asc" },
  });

  let updated = 0;

  for (const lesson of lessons) {
    let content: unknown = null;

    switch (lesson.lessonNumber) {
      case 1:
        content = doc(
          "本课讲述人类从依赖自然采集渔猎到主动生产粮食的根本性转变，这是人类文明第一次经济革命。",
          "课程涵盖采集渔猎时代、原始农耕与畜牧的产生、农业产生的历史影响、不同地区的食物生产特色（大河文明、海洋文明、古代美洲），以及农业发展推动私有制、阶级与国家产生的内在逻辑。",
          "重点掌握：原始农业产生的影响；各大文明农业生产差异。难点：农业发展→剩余产品→私有制→阶级→国家的完整逻辑链条。"
        );
        break;
      case 2:
        content = doc(
          "本课讲述新航路开辟后全球食物物种的双向大交流，即哥伦布大交换。",
          "课程涵盖美洲物种向外传播（玉米、马铃薯等传入欧亚非）、欧亚非物种传入美洲（小麦、水稻、马牛羊等）、食物物种交流带来的双重影响（人口激增、饮食丰富 vs 生态破坏、殖民掠夺）。",
          "重点掌握：明清时期美洲高产作物传入中国对清朝康乾盛世人口增长的核心推动作用。"
        );
        break;
      case 3:
        content = doc(
          "本课讲述现代食物生产、储备技术的进步以及粮食安全与食品安全问题。",
          "课程涵盖农业生产的现代化（机械化、杂交育种、无土栽培）、食物储备技术进步（冷链物流、国家粮食储备）、粮食安全问题（联合国粮农组织、中国粮食自给战略）、食品安全问题（《食品安全法》、18亿亩耕地红线）。",
          "应对粮食危机：科技层面培育高产良种，政策层面保护耕地完善储备体系，国际层面加强合作反对贸易壁垒。"
        );
        break;
      case 4:
        content = doc(
          "本课讲述古代生产工具从石器到铁器的演变历程，以及手工业工具与劳作方式的特点。",
          "课程涵盖农业工具演变（石器→青铜→铁器，灌溉工具翻车→筒车）、手工业工具与劳作方式（纺织、陶瓷，家庭/官营/私营手工业并存）、古代劳作特征总结（依托人力畜力、分散个体劳作、技术传承封闭）。",
          "核心关系：生产工具革新决定劳作方式变革，劳作方式反作用于工具革新，生产力发展是核心动力。"
        );
        break;
      case 5:
        content = doc(
          "本课讲述两次工业革命带来的生产方式变革和工厂制度的建立与影响。",
          "课程涵盖第一次工业革命（机器取代手工、工厂取代手工工场、工厂制度特点）、工业革命带来的生活变化（城市化加速 vs 贫富差距拉大）、第二次工业革命与大企业（流水线生产、垄断组织、现代企业管理制度）。",
          "工厂制度对工人的双重影响：规范劳动时间推动职业化，但工人沦为机器附庸、劳动异化。"
        );
        break;
      case 6:
        content = doc(
          "本课讲述二战后第三次科技革命的四大领域及其对劳作方式和社会发展的影响。",
          "课程涵盖信息技术、生物技术、航天技术、海洋技术四大领域，科技进步对劳作方式的改变（智能机器取代人工、远程办公、第三产业崛起），以及科技发展的双刃剑效应（生产力飞跃 vs 网络安全、结构性失业、伦理争议、数字鸿沟）。",
          "人类从工业时代迈入信息时代，知识经济成为经济增长核心动力。"
        );
        break;
      case 7:
        content = doc(
          "本课讲述商业贸易的起源与古代中国商业发展的全时间线。",
          "课程涵盖商业贸易起源（产品剩余→社会分工→物品交换→商业诞生）、古代世界商业发展（古埃及、古希腊、古罗马、阿拉伯帝国）、古代中国商业发展（商周工商食官→春秋私商崛起→秦汉统一→隋唐坊市分离→两宋坊市打破、交子出现→明清商帮票号）、古代商贸通道（陆上和海上丝绸之路）。",
          "重点掌握两宋商业革命：坊市界限打破、夜市草市普及、世界最早纸币交子、海外贸易空前繁荣。"
        );
        break;
      case 8:
        content = doc(
          "本课讲述世界市场形成的四个阶段和近代商业经营方式的革新。",
          "课程涵盖世界市场四阶段：新航路开辟雏形出现→早期殖民扩张进一步拓展→第一次工业革命初步形成→第二次工业革命最终形成；近代商业经营方式革新（股份公司、证券交易所、近代银行、百货公司、连锁商店、期货贸易）。",
          "核心转变：从商品输出为主（第一次工业革命）到资本输出为主（第二次工业革命）。"
        );
        break;
      case 9:
        content = doc(
          "本课讲述20世纪经济危机与二战后世界经济体系化、全球化对人类生活的影响。",
          "课程涵盖1929-1933年大萧条与贸易保护主义、二战后三大国际经济组织（世界银行、IMF、WTO）建立、经济全球化表现（商品资本人员技术自由流动、跨国公司）、现代生活变化（电商、移动支付、消费一体化）及问题（贫富差距、贸易保护主义回潮）。",
          "二战后多边贸易体系建立，贸易自由化成为主流，区域经济集团化和全球化并行发展。"
        );
        break;
      case 10:
        content = doc(
          "本课讲述村落的产生、集镇的兴起以及古代中国与西方城市特征的差异。",
          "课程涵盖村落产生（农耕定居后原始村落的多重功能）、集镇兴起（手工业商业分离、交通要道自发形成集市）、古代城市特征对比（中国政治军事功能为主 vs 西方工商业功能突出、城市自治传统）、古代民居（因地制宜：四合院、窑洞、吊脚楼、徽派建筑、客家土楼）。",
          "影响古代城市布局的因素：政治制度、军事防御、自然地理、经济发展、传统文化礼制。"
        );
        break;
      case 11:
        content = doc(
          "本课讲述工业革命推动的西方城市化进程、城市化带来的问题及中国近代城市化特点。",
          "课程涵盖西方城市化进程（英国率先完成→欧美全面城市化）、城市化问题（住房拥挤、环境污染、交通拥堵、公共卫生恶劣）及治理措施、中国近代城市化（通商口岸被动开启、发展不均衡、城乡二元结构）、中国现代城市化（改革开放后高速发展、城市群崛起）。",
          "中国近代城市化的核心特征：被动性、不均衡性、殖民色彩与近代化并存。"
        );
        break;
      case 12:
        content = doc(
          "本课讲述古代水陆交通建设以及近代工业革命带来的交通变革。",
          "课程涵盖古代陆路交通（中国秦汉驰道、古罗马帝国大道）、古代水路交通（中国大运河、郑和下西洋、地中海航路）、近代交通变革（蒸汽机车铁路时代到来、蒸汽轮船取代帆船）。",
          "古代交通建设的共同目的：巩固统治、加强经济文化交流、满足军事调动和政令传递需求。"
        );
        break;
      case 13:
        content = doc(
          "本课讲述现代交通运输的立体化发展成就及其对社会的总体影响。",
          "课程涵盖现代陆路交通（高速公路网络、中国高铁领跑全球）、航空与海运（民航客机普及、集装箱货轮全球物流一体化）、交通发展总体影响（缩短时空距离、推动城市化全球化、带动物流业）、中国交通建设成就（全球最大高铁高速公路网、港珠澳大桥等超级工程）。",
          "交通发展是一把双刃剑：推动全球化的同时也带来交通拥堵、尾气污染等问题。"
        );
        break;
      case 14:
        content = doc(
          "本课讲述古代疫病流行与防疫措施，以及中外古代医学成就。",
          "课程涵盖古代疫病流行（雅典瘟疫、罗马瘟疫、中国天花鼠疫）及影响、古代防疫措施（隔离、清污、掩埋尸体）、中国医学成就（《黄帝内经》《伤寒杂病论》《本草纲目》、针灸望闻问切）、西方医学（希波克拉底体液学说）。",
          "古代疫病的双重影响：消极面是人口锐减社会动荡，积极面是推动公共卫生意识觉醒和医学技术进步。"
        );
        break;
      case 15:
        content = doc(
          "本课讲述现代医疗卫生体系的内容、成就以及当代公共卫生面临的挑战。",
          "课程涵盖现代医疗卫生体系三大板块（基础医疗、公共卫生、医疗保障）、现代医疗成就（天花消灭、人均寿命提升）、当代公共卫生挑战（新型病毒、抗生素滥用、全球治理不均衡）、新中国医疗卫生成就（爱国卫生运动、基层医疗体系、新冠疫情防控）。",
          "核心启示：全球卫生治理合作是应对公共卫生挑战的必由之路。"
        );
        break;
    }

    if (content) {
      await db.lesson.update({
        where: { id: lesson.id },
        data: { content },
      });
      console.log(`第${lesson.lessonNumber}课: ${lesson.title} - 已添加内容`);
      updated++;
    }
  }

  console.log(`\n完成！共更新 ${updated} 门课程内容`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
