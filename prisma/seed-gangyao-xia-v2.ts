import { PrismaClient } from "@prisma/client";

const db = new PrismaClient();

function doc(...ps: string[]) {
  return { type: "doc", content: ps.map((t) => ({ type: "paragraph", content: [{ type: "text", text: t }] })) };
}

async function addKp(lessonId: string, title: string, content: string[], opts?: { d?: number; tags?: string[]; exam?: string }) {
  return db.knowledgePoint.create({
    data: {
      lessonId, title,
      difficulty: opts?.d || 2,
      tags: opts?.tags || [],
      sortOrder: 1,
      content: doc(...content),
      examRequirements: opts?.exam,
    },
  });
}

