// 主逻辑：将思维导图写入每课第一个知识点的 mindMapJson
// ═══════════════════════════════════════════════════════════════
const mindMaps: Record<number, MindNode> = {
  1: lesson1Map, 2: lesson2Map, 3: lesson3Map,
  4: lesson4Map, 5: lesson5Map, 6: lesson6Map,
  7: lesson7Map, 8: lesson8Map, 9: lesson9Map,
  10: lesson10Map, 11: lesson11Map, 12: lesson12Map,
  13: lesson13Map, 14: lesson14Map, 15: lesson15Map,
  16: lesson16Map, 17: lesson17Map, 18: lesson18Map,
};

async function main() {
  console.log("开始为选择性必修1添加思维导图...\n");

  const textbook = await db.textbook.findFirst({
    where: { title: { contains: "选择性必修1" } },
  });
  if (!textbook) {
    console.error("未找到选择性必修1教材");
    return;
  }

  const lessons = await db.lesson.findMany({
    where: { unit: { textbookId: textbook.id } },
    orderBy: { lessonNumber: "asc" },
    include: { knowledgePoints: { orderBy: { sortOrder: "asc" }, take: 1 } },
  });

  let updated = 0;

  for (const lesson of lessons) {
    const mapData = mindMaps[lesson.lessonNumber];
    if (!mapData) {
      console.log(`第${lesson.lessonNumber}课: 无思维导图数据，跳过`);
      continue;
    }

    if (lesson.knowledgePoints.length === 0) {
      console.log(`第${lesson.lessonNumber}课: 无知识点，跳过`);
      continue;
    }

    const kpId = lesson.knowledgePoints[0].id;
    await db.knowledgePoint.update({
      where: { id: kpId },
      data: { mindMapJson: mapData },
    });

    console.log(`第${lesson.lessonNumber}课: ${lesson.title} → 知识点「${lesson.knowledgePoints[0].title}」已写入思维导图`);
    updated++;
  }

  console.log(`\n完成！共为 ${updated} 课写入思维导图数据`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
