async function main() {
  console.log("开始更新选择性必修1课程内容...\n");

  const textbook = await db.textbook.findFirst({
    where: { title: { contains: "选择性必修1" } },
  });
  if (!textbook) { console.error("未找到教材"); return; }

  const lessons = await db.lesson.findMany({
    where: { unit: { textbookId: textbook.id } },
    orderBy: { lessonNumber: "asc" },
  });

  let updated = 0;

  for (const lesson of lessons) {
    const content = C[lesson.lessonNumber];
    if (!content) {
      console.log(`第${lesson.lessonNumber}课: 无内容数据，跳过`);
      continue;
    }

    await db.lesson.update({
      where: { id: lesson.id },
      data: { content: doc(...content) },
    });

    console.log(`第${lesson.lessonNumber}课: ${lesson.title} → 已更新（${content.length}段）`);
    updated++;
  }

  console.log(`\n完成！共更新 ${updated} 门课程内容`);
}

