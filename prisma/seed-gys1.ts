import { PrismaClient } from "@prisma/client";

const db = new PrismaClient();

function doc(...ps: string[]) {
  return { type: "doc", content: ps.map((t) => ({ type: "paragraph", content: [{ type: "text", text: t }] })) };
}

// 工具函数：创建教材+单元+课程+知识点
async function createLesson(
  db: any, unitId: string, lessonNumber: number,
  data: { title: string; learningObjectives: string; keyTerms: string; summary: string; content: string[] },
  kps: Array<{ title: string; difficulty: number; tags: string[]; content: string[]; keyConcepts?: Array<{ term: string; definition: string }> }>
) {
  const lesson = await db.lesson.create({
    data: {
      unitId, title: data.title, lessonNumber, sortOrder: lessonNumber,
      learningObjectives: data.learningObjectives, keyTerms: data.keyTerms,
      summary: data.summary, content: doc(...data.content),
    },
  });
  for (let i = 0; i < kps.length; i++) {
    const kp = kps[i];
    await db.knowledgePoint.create({
      data: {
        lessonId: lesson.id, title: kp.title, difficulty: kp.difficulty,
        tags: kp.tags, sortOrder: i + 1, content: doc(...kp.content),
        ...(kp.keyConcepts ? { keyConcepts: kp.keyConcepts } : {}),
      },
    });
  }
  return lesson;
}

