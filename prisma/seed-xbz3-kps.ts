async function main() {
  console.log("为选必3添加知识点...\n");

  const textbook = await db.textbook.findFirst({
    where: { title: { contains: "选择性必修3" } },
  });
  if (!textbook) { console.error("未找到选必3"); return; }

  const lessons = await db.lesson.findMany({
    where: { unit: { textbookId: textbook.id } },
    include: { knowledgePoints: true },
    orderBy: { lessonNumber: "asc" },
  });

  let totalCreated = 0;

  for (const lesson of lessons) {
    const kps = kpData[lesson.lessonNumber];
    if (!kps) {
      console.log(`  跳过: ${lesson.title} (无知识点定义)`);
      continue;
    }

    // Delete existing KPs
    if (lesson.knowledgePoints.length > 0) {
      await db.knowledgePoint.deleteMany({ where: { lessonId: lesson.id } });
    }

    for (let i = 0; i < kps.length; i++) {
      const kp = kps[i];
      await db.knowledgePoint.create({
        data: {
          lessonId: lesson.id,
          title: kp.title,
          difficulty: kp.difficulty,
          tags: kp.tags,
          sortOrder: i + 1,
          content: doc(...kp.content),
          keyConcepts: kp.keyConcepts ?? [],
        },
      });
      totalCreated++;
    }

    console.log(`  ✓ 第${lesson.lessonNumber}课 ${lesson.title} (${kps.length}个知识点)`);
  }

  console.log(`\n完成！创建 ${totalCreated} 个知识点`);
}

main().catch(e => { console.error(e); process.exit(1); }).finally(() => db.$disconnect());
