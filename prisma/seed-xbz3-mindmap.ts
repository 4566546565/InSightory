async function main() {
  console.log("为选必3添加思维导图...\n");

  const textbook = await db.textbook.findFirst({
    where: { title: { contains: "选择性必修3" } },
  });
  if (!textbook) { console.error("未找到选必3"); return; }

  const lessons = await db.lesson.findMany({
    where: { unit: { textbookId: textbook.id } },
    include: { knowledgePoints: { orderBy: { sortOrder: "asc" }, take: 1 } },
    orderBy: { lessonNumber: "asc" },
  });

  let updated = 0;

  for (const lesson of lessons) {
    const mindmap = lessonMaps[lesson.lessonNumber];
    if (!mindmap) {
      console.log(`  跳过: ${lesson.title} (无思维导图)`);
      continue;
    }

    const firstKP = lesson.knowledgePoints[0];
    if (!firstKP) {
      console.log(`  跳过: ${lesson.title} (无知识点)`);
      continue;
    }

    await db.knowledgePoint.update({
      where: { id: firstKP.id },
      data: { mindMapJson: mindmap },
    });

    function countNodes(node: MindNode): number {
      let c = 1;
      if (node.children) for (const ch of node.children) c += countNodes(ch);
      return c;
    }

    console.log(`  ✓ 第${lesson.lessonNumber}课 ${lesson.title} (${countNodes(mindmap)}个节点)`);
    updated++;
  }

  console.log(`\n完成！更新 ${updated} 课思维导图`);
}

main().catch(e => { console.error(e); process.exit(1); }).finally(() => db.$disconnect());
